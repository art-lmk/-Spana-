export function generateNitaMockFundis(): Fundi[] {
  return NITA_RAW_ROWS.map((row, idx) => {
    const name = String(row[0]);
    const category = String(row[1]);
    const certLevel = String(row[2]);
    const neighborhood = String(row[3]);
    const lat = Number(row[4]);
    const lng = Number(row[5]);
    const rating = Number(row[6]);
    const matchScore = Number(row[7]);
    const hourlyRateKes = Number(row[8]);
    const fixedInspectionFeeKes = Number(row[9]);
    const phone = String(row[10]);
    const whatsapp = String(row[11]);
    const experienceYears = Number(row[12]);
    const jobsCompleted = Number(row[13]);
    const isNitaAccredited = String(row[14]) === 'true';
    const rawSkills = String(row[15]);
    const rawTools = String(row[16]);

    const skills = rawSkills.split(',').map(s => s.trim()).filter(Boolean);
    const toolsEquipment = rawTools.split(',').map(t => t.trim()).filter(Boolean);

    const bio = isNitaAccredited
      ? `${certLevel} certified artisan with ${experienceYears}+ years hands-on field expertise in ${neighborhood} and wider Nairobi. Verified NITA standard compliance.`
      : `Skilled artisan with ${experienceYears}+ years hands-on apprenticeship mastery in ${neighborhood}. Peer guild vetted, high customer satisfaction, and eligible for NITA Recognition of Prior Learning (RPL) certification.`;

    return {
      id: `nita-artisan-${idx + 1}-${name.toLowerCase().replace(/[^a-z0-9]/g, '-')}`,
      name,
      avatarUrl: NITA_AVATARS[idx % NITA_AVATARS.length],
      phone,
      whatsapp,
      primaryCategory: category,
      additionalCategories: [],
      skills,
      bio,
      experienceYears,
      hourlyRateKes,
      fixedInspectionFeeKes,
      rating,
      reviewCount: Math.round(jobsCompleted * 0.75),
      jobsCompleted,
      isVerified: true,
      idVerified: true,
      backgroundChecked: true,
      isAvailableNow: true,
      responseTimeMinutes: 12 + (idx % 3) * 5,
      location: {
        lat,
        lng,
        neighborhood,
        address: `${neighborhood}, Nairobi, Kenya`,
        city: 'Nairobi'
      },
      toolsEquipment,
      emergencyAvailable: true,
      nitaAccredited: isNitaAccredited,
      nitaCertificationLevel: isNitaAccredited ? certLevel : 'Apprenticeship Trained (RPL Eligible)',
      nitaTradeTestNo: isNitaAccredited ? `NITA/TT/2024/${1100 + idx}` : undefined,
      accreditationStatus: isNitaAccredited ? 'nita_accredited' : 'rpl_candidate',
      rplEligible: !isNitaAccredited,
      rplStatus: !isNitaAccredited ? 'not_applied' : undefined,
      experienceRoute: isNitaAccredited ? 'formal_vocational' : 'informal_apprenticeship',
      matchScore,
      matchReasons: [
        isNitaAccredited ? `${certLevel} Certified (NITA)` : 'Apprenticeship Mastered • RPL Candidate',
        `Dataset Match Score: ${matchScore}%`,
        `Specialization: ${skills.slice(0, 2).join(', ')}`
      ],
      reviews: [
        {
          id: `rev-nita-${idx}-1`,
          authorName: 'Verified Homeowner',
          rating: 5,
          date: '2026-02-18',
          comment: `Exceptional workmanship from ${name}. Certified NITA standards were immediately evident in their methodology and diagnostic precision.`,
          jobType: `${category} Installation & Triage`,
          verifiedJob: true
        }
      ],
      portfolio: [
        {
          id: `port-nita-${idx}-1`,
          title: `Certified ${category} Project`,
          description: `Comprehensive project completed to NITA industrial standard specifications in ${neighborhood}.`,
          imageUrl: 'https://images.unsplash.com/photo-1581094794329-c8112a89af12?auto=format&fit=crop&q=80&w=800',
          category,
          completionDate: '2026-02-01'
        }
      ]
    };
  });
}
